function updateCanvasScale() {
  if (window.matchMedia("(max-width: 700px)").matches) {
    canvasFit.style.transform = "none";
    return;
  }
  const availableWidth = Math.max(0, canvasViewport.clientWidth - 24);
  const availableHeight = Math.max(0, canvasViewport.clientHeight - 24);
  const fitScale = Math.min(availableWidth / 1280, availableHeight / 720);
  canvasFit.style.transform = `scale(${fitScale})`;
}

if ("ResizeObserver" in window) {
  new ResizeObserver(updateCanvasScale).observe(canvasViewport);
} else {
  window.addEventListener("resize", updateCanvasScale);
}

sectionTabs.forEach(tab => {
  tab.addEventListener("click", () => showSlide(Number(tab.dataset.start)));
});

function updateSectionTabs() {
  sectionTabs.forEach(tab => {
    const start = Number(tab.dataset.start);
    const end = Number(tab.dataset.end);
    const active = Number.isInteger(end) && currentIndex >= start && currentIndex <= end;
    if (active) tab.setAttribute("aria-current", "true");
    else tab.removeAttribute("aria-current");
  });
}

function escapeHtml(value) {
  return String(value).replace(/[&<>"']/g, character => ({
    "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;"
  })[character]);
}

function renderCards(cards) {
  return `<div class="card-grid">${cards.map(card => `
    <article class="info-card">
      <span class="card-number">${escapeHtml(card.number)}</span>
      <h3>${escapeHtml(card.title)}</h3>
      <p>${escapeHtml(card.text)}</p>
    </article>`).join("")}</div>`;
}

